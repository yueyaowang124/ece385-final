/*=============================================================================
 * harry_potter_score.h  —  Hedwig's Theme (Harry Potter) 完整曲谱
 *
 * 包含两种格式：
 *   1. SONG_HARRY_GAME[]   游戏下落 tile 格式  (game_event_t)
 *   2. SCORE_HARRY_AUTO[]  自动演奏格式        (PeppaNote)
 *
 * 使用方法：
 *   在 main.c 里 SONG_HARRY / SCORE_PEPPA_AUTO 定义之后 #include 本文件，然后：
 *
 *   游戏曲谱替换：
 *     把 SONG_TABLES[] 里对应 Harry 的位置从 SONG_HARRY 换成 SONG_HARRY_GAME，
 *     并把 SONG3_LEN 换成 HARRY_GAME_LEN。
 *
 *   自动演奏替换：
 *     在 run_auto_mode() 里，当 sel_song==2 时把
 *     SCORE_PEPPA_AUTO / PEPPA_LEN 换成 SCORE_HARRY_AUTO / HARRY_AUTO_LEN。
 *
 * ─── 音符参照 ────────────────────────────────────────────────────────────────
 *   半音 (相对 C4=0):
 *     C#4=1  D4=2  F4=5  G4=7  Ab4=8  A4=9  Bb4=10  B4=11
 *     C5=12  C#5=13  D5=14  Eb5=15  E5=16  F5=17
 *
 *   列分配 (游戏):
 *     A(0)=低音  C#4/D4/F4
 *     S(1)=中低  G4/A4/B4
 *     D(2)=中高  Bb4/C5/C#5/Eb5
 *     F(3)=高    D5/E5/F5
 *
 * ─── 时值 (游戏) ─────────────────────────────────────────────────────────────
 *   八分=15f  四分=30f  附点四分=45f
 *   二分=60f  附点二分=90f  附点全音=180f
 *   (f = 帧, ~16ms/帧)
 *
 * ─── 时值 (自动演奏) ──────────────────────────────────────────────────────────
 *   TICK_MS=125ms: e=2  q=3  dq=5  h=7  dh=10  w=13  dw=20
 *
 * ─── DDS Phase Increment (PHASE_INC_TABLE 索引相对 C4_INDEX=24) ──────────────
 *   C#4=11903  D4=12607  F4=14999  G4=16838  Ab4=17838
 *   A4=18897   Bb4=20021  B4=21213  C5=22473  C#5=23806
 *   D5=25215   Eb5=26714  E5=28304  F5=29998
 *   (低八度参照) D3=6305  F3=7497  G3=9448  A3=10608  C4=11236
 *=============================================================================*/

